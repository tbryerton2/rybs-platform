import { readdirSync, readFileSync } from "node:fs";
import { spawnSync } from "node:child_process";

// Only the local Docker database is used. No project credentials or hosted writes.
const container = "supabase_db_rybs-platform";
const database = `rybs_pricing_test_${process.pid}_${Date.now()}`;
let created = false;

function docker(args, input) {
  const result = spawnSync("docker", ["exec", "-i", container, ...args], {
    input,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`${args[0]} failed:\n${result.stdout?.slice(-3000)}\n${result.stderr?.slice(-6000)}`);
  }
  return result.stdout;
}

function sql(input) {
  return docker(["psql", "-U", "postgres", "-d", database, "-v", "ON_ERROR_STOP=1"], input);
}

try {
  // Infrastructure definitions only: no existing application schema, data or ACLs.
  const bootstrap = docker([
    "pg_dump", "-U", "postgres", "-d", "postgres", "--schema-only",
    "--schema=auth", "--schema=storage", "--schema=extensions",
    "--no-owner", "--no-privileges",
  ]);
  docker(["createdb", "-U", "postgres", "-T", "template0", database]);
  created = true;
  sql(bootstrap);
  sql(`
    create extension if not exists "uuid-ossp" with schema extensions;
    create extension if not exists pgcrypto with schema extensions;
    grant usage on schema public, auth, extensions to anon, authenticated, service_role;
    alter default privileges for role postgres revoke all on tables from anon, authenticated, service_role;
    alter default privileges for role postgres in schema public revoke all on tables from anon, authenticated, service_role;
    alter default privileges for role postgres revoke all on sequences from anon, authenticated, service_role;
    alter default privileges for role postgres in schema public revoke all on sequences from anon, authenticated, service_role;
    alter default privileges for role postgres in schema public revoke execute on functions from anon, authenticated, service_role;
    create table public.grants_test_unexposed (id bigint generated by default as identity);
  `);

  const migrations = readdirSync("supabase/migrations").filter((name) => name.endsWith(".sql")).sort();
  const replay = migrations.map((name) => `\n-- ${name}\n${readFileSync(`supabase/migrations/${name}`, "utf8")}`).join("\n");
  sql(replay);
  console.log(`Replayed ${migrations.length} migrations without automatic grants.`);
  sql(readFileSync("tests/product-positions.sql", "utf8"));
  console.log("Product positions: atomic full-list validation, tenant isolation, visibility, append and idempotency passed.");

  const pricingMigration = migrations.find((name) => name.endsWith("_consolidate_pricing_content.sql"));
  if (!pricingMigration) throw new Error("Missing pricing content migration");
  const pricingSql = readFileSync(`supabase/migrations/${pricingMigration}`, "utf8");
  sql(readFileSync("tests/fixtures/pricing-content/setup.sql", "utf8"));
  sql(pricingSql);
  sql(readFileSync("tests/fixtures/pricing-content/assert.sql", "utf8"));
  sql(pricingSql);
  sql(readFileSync("tests/fixtures/pricing-content/assert.sql", "utf8"));
  sql(`update public.dumpster_product_settings set truck_load_estimate=null, size_guide_examples=null
    where business_id='11111111-1111-4111-8111-111111111101' and dumpster_product_id='ten';`);
  sql(pricingSql);
  sql(`do $$ begin
    assert (select truck_load_estimate is null and size_guide_examples is null
      from public.dumpster_product_settings where business_id='11111111-1111-4111-8111-111111111101' and dumpster_product_id='ten'),
      'Idempotent migration must not resurrect user-cleared data';
  end $$;`);
  console.log("Pricing content: normalized matching, ambiguous/unmatched rows, tenant isolation, draft preservation, conflicts, exact cleanup, and idempotency passed.");

  const singleScreenMigration = migrations.find((name) => name.endsWith("_pricing_page_single_screen.sql"));
  if (!singleScreenMigration) throw new Error("Missing single-screen pricing migration");
  const singleScreenSql = readFileSync(`supabase/migrations/${singleScreenMigration}`, "utf8");
  sql(readFileSync("tests/fixtures/pricing-content/single-screen-setup.sql", "utf8"));
  sql(singleScreenSql);
  sql(readFileSync("tests/fixtures/pricing-content/single-screen-assert.sql", "utf8"));
  sql(singleScreenSql);
  sql(readFileSync("tests/fixtures/pricing-content/single-screen-assert.sql", "utf8"));
  sql(`update public.pricing_page_settings set included_items='[]', headline='Saved later'
    where business_id='11111111-1111-4111-8111-111111111101';`);
  sql(singleScreenSql);
  sql(`do $$ begin
    assert (select included_items='[]' and headline='Saved later' and jsonb_array_length(archived_cms)>0
      from public.pricing_page_settings where business_id='11111111-1111-4111-8111-111111111101'), 'Repeated migration preserves later saves and archive';
  end $$;`);
  console.log("Single-screen Pricing: published wins, differing/draft-only copy archived, tenant isolation, rollback rows and idempotency passed.");

} finally {
  if (created) docker(["dropdb", "-U", "postgres", "--if-exists", database]);
}
