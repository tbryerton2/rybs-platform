create extension if not exists pgcrypto;

create table if not exists public.dumpsters (
  id uuid primary key default gen_random_uuid(),
  equipment_id text not null unique,
  display_name text not null,
  size text not null,
  dimensions text,
  capacity_notes text,
  active boolean not null default true,
  operational_status text not null,
  maintenance_status text not null default 'Current',
  condition_notes text,
  in_service_date date,
  notes text,
  serial_number text,
  manufacturer text,
  model text,
  yard_location text,
  service_status text not null,
  last_service_date date,
  next_service_date date,
  last_inspection_date date,
  next_inspection_due date,
  asset_tag text,
  tracker_label text,
  tracker_enabled boolean not null default false,
  tracker_provider text,
  tracker_id text,
  tracker_installation_date date,
  tracker_last_check_in timestamptz,
  tracker_status text not null default 'Not installed',
  tracker_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint dumpsters_equipment_id_not_blank check (char_length(trim(equipment_id)) > 0),
  constraint dumpsters_display_name_not_blank check (char_length(trim(display_name)) > 0),
  constraint dumpsters_size_not_blank check (char_length(trim(size)) > 0),
  constraint dumpsters_operational_status_check
    check (operational_status in ('Available', 'On rent', 'In yard', 'Maintenance hold')),
  constraint dumpsters_maintenance_status_check
    check (maintenance_status in ('Current', 'Due soon', 'Needs service')),
  constraint dumpsters_service_status_check
    check (service_status in ('Ready', 'Inspection due', 'Out of service')),
  constraint dumpsters_tracker_status_check
    check (tracker_status in ('Online', 'Offline', 'Needs attention', 'Not installed'))
);

create index if not exists dumpsters_active_idx
  on public.dumpsters (active);

create index if not exists dumpsters_active_size_idx
  on public.dumpsters (active, size);

create index if not exists dumpsters_operational_status_idx
  on public.dumpsters (operational_status);

create index if not exists dumpsters_next_service_date_idx
  on public.dumpsters (next_service_date);

drop trigger if exists dumpsters_set_updated_at on public.dumpsters;
create trigger dumpsters_set_updated_at
before update on public.dumpsters
for each row execute function public.set_updated_at();

